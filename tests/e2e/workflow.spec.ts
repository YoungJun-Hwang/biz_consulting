import {test,expect} from '@playwright/test';
test('모바일 진단 제출, 결과 유지, 관리자 검색과 필터',async({page})=>{
 await page.setViewportSize({width:390,height:844});
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('/');
 await expect(page.getByRole('heading',{name:/우리 사업의 건강한 내일/})).toBeVisible();
 await page.getByRole('button',{name:'다음 단계'}).click();
 await expect(page.getByText('필수 항목을 입력해 주세요.')).toHaveCount(3);
 await page.getByLabel('사업장명').fill('온기 식당');
 await page.getByLabel('업종', {exact:false}).selectOption('음식점');
 await page.getByLabel('사업장 지역').fill('서울시 마포구');
 await page.getByLabel('직원 수').fill('3');
 await page.getByRole('button',{name:'다음 단계'}).click();
 await page.getByLabel('월평균 매출').fill('5000');
 await page.getByLabel('원재료·매입비').fill('1500');
 await page.getByLabel('인건비').fill('1000');
 await page.getByLabel('임차료').fill('500');
 await page.getByLabel('기타 운영비').fill('500');
 await page.getByRole('button',{name:'다음 단계'}).click();
 await page.getByLabel('재방문 고객 비율').fill('60');
 await page.getByRole('radio',{name:'4 적극 활용'}).check();
 await page.getByRole('button',{name:'진단 결과 확인'}).click();
 await expect(page).toHaveURL(/results\?id=/);
 await expect(page.getByRole('heading',{name:/온기 식당의/})).toBeVisible();
 await expect(page.getByText('1,500',{exact:false}).first()).toBeVisible();
 await page.reload();
 await expect(page.getByRole('heading',{name:/온기 식당의/})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.goto('/admin');
 await expect(page.getByRole('cell',{name:'온기 식당 직원 3명'})).toBeVisible();
 await page.getByLabel('사업장 검색').fill('없는 사업장');
 await expect(page.getByText('검색 결과가 없습니다')).toBeVisible();
 await page.getByLabel('사업장 검색').fill('마포');
 await page.getByLabel('업종 필터').selectOption('음식점');
 await expect(page.getByRole('link',{name:'온기 식당 결과 보기'})).toBeVisible();
 await page.getByRole('link',{name:'온기 식당 결과 보기'}).click();
 await expect(page.getByRole('heading',{name:/온기 식당의/})).toBeVisible();
 expect(errors).toEqual([]);
});
test('데스크톱 레이아웃과 빈 결과·대시보드',async({page})=>{
 await page.setViewportSize({width:1440,height:1000});
 await page.goto('/');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.goto('/results?id=missing');
 await expect(page.getByRole('heading',{name:'아직 진단 결과가 없어요'})).toBeVisible();
 await page.goto('/admin');
 await expect(page.getByRole('heading',{name:'아직 제출된 진단이 없습니다'})).toBeVisible();
 await expect(page.getByRole('button',{name:'데이터 내보내기'})).toBeDisabled();
});
